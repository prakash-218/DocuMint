# may not belong to a customer yet)
email_file = Table(
    'email_file', metadata,
    _id('file_id'),
    _ref('org_id', 'organization.org_id', 'CASCADE'),
    _ref('message_id', 'email_message.message_id', 'CASCADE'),
    Column('file_name', String(255), nullable=False),
    Column('content_type', String(100), nullable=False),
    Column('file_size', BigInteger, nullable=False),
    Column('storage_key', String(300), nullable=False),
    Column('content_hash', String(64)),
)

audit_log = Table(
    'audit_log', metadata,
    _id('audit_id'),
    Column('org_id', UUID(as_uuid=False), index=True),
    Column('table_name', String(100), nullable=False),
    Column('record_id', String(100), nullable=False),
    Column('action_type', String(10), nullable=False),
    Column('field_name', String(100)),
    Column('old_value', Text),
    Column('new_value', Text),
    Column('changed_by', String(255)),
    Column('changed_at', TIMESTAMP(timezone=True), nullable=False, server_default=func.now(), index=True),
    Column('additional_info', Text),
)
