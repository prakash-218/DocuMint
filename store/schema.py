metadata = MetaData(naming_convention={
    'ix': 'ix_%(table_name)s_%(column_0_name)s',
    'uq': 'uq_%(table_name)s_%(column_0_name)s',
    'ck': 'ck_%(table_name)s_%(constraint_name)s',
    'fk': 'fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s',
    'pk': 'pk_%(table_name)s',
})


def _id(name):
    return Column(name, UUID(as_uuid=False), primary_key=True, server_default=text('gen_random_uuid()'))


def _ref(name, target, ondelete=None, nullable=False, index=True):
    return Column(name, UUID(as_uuid=False), ForeignKey(target, ondelete=ondelete), nullable=nullable, index=index)


def _created():
    return Column('created_at', TIMESTAMP(timezone=True), nullable=False, server_default=func.now())


