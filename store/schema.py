"""
PostgreSQL schema (SQLAlchemy Core). Alembic migrations in alembic/ are built from this.

Conventions: UUID primary keys generated by the database, money as NUMERIC(15,4),
JSONB for open-ended settings (organization profile, document details, layouts),
timestamps with time zone, and CHECK constraints instead of enums so adding a
status is a one-line migration.
"""

from sqlalchemy import (BigInteger, Boolean, CheckConstraint, Column, Date, ForeignKey, ForeignKeyConstraint,
                        Index, Integer, LargeBinary, MetaData, Numeric, PrimaryKeyConstraint, String, Table, Text,
                        UniqueConstraint, func, text)
